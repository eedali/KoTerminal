export function translate(language, key, vars) {
    const table = STRINGS[language] ?? STRINGS.en;
    let text = table[key] ?? STRINGS.en[key] ?? key;
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
    return text;
}

export const currentLanguage = () => window.useAppStore?.getState?.().language ?? 'en';

/** Hook: a translate function that re-renders the component when KoBar's language changes. */
export function useT() {
    const language = window.useAppStore((state) => state.language);
    return (key, vars) => translate(language, key, vars);
}

export const LANGUAGES = Object.keys(STRINGS);
